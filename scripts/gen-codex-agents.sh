#!/usr/bin/env bash
# Renders the generated agent files from the plugin's Claude-format agents:
# - plugins/harness/agents/reviewer-intermediate.md: reviewer.md's body under the intermediate review's
#   frontmatter (model, effort, description), so the two reviewers never drift apart;
# - the Codex agent definitions (.codex/agents/*.toml). Codex plugins cannot carry agents, so the template
#   ships these files.
# tests/codex-agents.sh fails when the committed files differ from a fresh render.
# Usage: scripts/gen-codex-agents.sh [<codex out dir> [<reviewer-intermediate.md out path>]]
set -eu
repo=$(cd "$(dirname "$0")/.." && pwd -P)
out=${1:-"$repo/template/{% if use_codex %}.codex{% endif %}/agents"}
src=$repo/plugins/harness/agents
mid=${2:-"$src/reviewer-intermediate.md"}
# Model ids and efforts from spec §3 Spike findings F12 (the Codex column of docs/harness/models.md).
STRONG_MODEL='gpt-6-luna' STRONG_EFFORT=high
FAST_MODEL='gpt-6-luna' FAST_EFFORT=medium
# The intermediate reviewer in Claude Code (the Claude table of docs/harness/models.md).
MID_MODEL=sonnet MID_EFFORT=medium
MID_DESCRIPTION="Reviews the commits of one task or batch against the parts of the change those tasks name, adversarially and in a context separate from the implementer - spec compliance with a scenario-to-test map, then code quality, then over-engineering - and returns a verdict. Use for task and batch reviews and their re-reviews during execution; the final whole-branch review uses the reviewer agent. Same instructions as the reviewer agent, on a lighter model and effort; dispatch it with the model from your agent's section of docs/harness/models.md."
mkdir -p "$out" "$(dirname "$mid")"

field() { sed -n "2,/^---\$/s/^$1: //p" "$2" | head -n 1; }
body() { awk 'n >= 2 { print } /^---$/ { n++ }' "$1"; }

{
  printf -- '---\n'
  printf '# Generated by scripts/gen-codex-agents.sh from reviewer.md. Do not edit; edit reviewer.md and rerun it.\n'
  printf 'name: reviewer-intermediate\n'
  printf 'description: %s\n' "$MID_DESCRIPTION"
  printf 'model: %s\neffort: %s\n' "$MID_MODEL" "$MID_EFFORT"
  printf 'maxTurns: %s\n' "$(field maxTurns "$src/reviewer.md")"
  printf 'tools: %s\n' "$(field tools "$src/reviewer.md")"
  printf -- '---\n%s\n' "$(body "$src/reviewer.md")"
} > "$mid"

emit() { # <src md> <name> <model> <effort> <sandbox>
  local b
  b=$(body "$1")
  case "$b" in *"'''"*) echo "gen-codex-agents: $1 contains ''' and cannot be a TOML literal string" >&2; exit 1 ;; esac
  {
    printf '# Generated by scripts/gen-codex-agents.sh from plugins/harness/agents/%s. Do not edit.\n' "$(basename "$1")"
    printf 'name = "%s"\n' "$2"
    printf 'description = %s\n' "$(field description "$1" | jq -Rs 'rtrimstr("\n")')"
    printf 'model = "%s"\n' "$3"
    printf 'model_reasoning_effort = "%s"\n' "$4"
    printf 'sandbox_mode = "%s"\n' "$5"
    printf "developer_instructions = '''\n%s\n'''\n" "$b"
  } > "$out/$2.toml"
}

emit "$src/implementer.md" harness-implementer "$FAST_MODEL" "$FAST_EFFORT" workspace-write
emit "$src/reviewer.md" harness-reviewer "$STRONG_MODEL" "$STRONG_EFFORT" read-only
emit "$mid" harness-reviewer-intermediate "$FAST_MODEL" "$FAST_EFFORT" read-only
